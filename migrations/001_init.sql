-- суммы в NUMERIC, не в float
CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login         TEXT        NOT NULL CHECK (login = lower(login) AND length(login) BETWEEN 1 AND 64),
  name          TEXT        NOT NULL CHECK (length(btrim(name)) > 0),
  role          TEXT        NOT NULL CHECK (role IN ('admin', 'user')),
  password_hash TEXT        NOT NULL,
  -- админ из .env, синхронизируется при старте
  is_env_admin  BOOLEAN     NOT NULL DEFAULT false,
  created_at    DATE        NOT NULL DEFAULT CURRENT_DATE,
  CONSTRAINT users_env_admin_is_admin CHECK (NOT is_env_admin OR role = 'admin')
);
CREATE UNIQUE INDEX users_login_lower_uq ON users (lower(login));
CREATE UNIQUE INDEX users_single_env_admin_uq ON users (is_env_admin) WHERE is_env_admin;

CREATE TABLE recurring_payments (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT          NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  amount      NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  currency    CHAR(3)       NOT NULL CHECK (currency IN ('RUB', 'USD', 'EUR')),
  periodicity TEXT          NOT NULL DEFAULT 'monthly' CHECK (periodicity = 'monthly'),
  -- день месяца; если его нет — последний день
  day         SMALLINT      NOT NULL CHECK (day BETWEEN 1 AND 31),
  start_date  DATE          NOT NULL,
  active      BOOLEAN       NOT NULL DEFAULT true,
  created_at  DATE          NOT NULL DEFAULT CURRENT_DATE,
  created_by  BIGINT        REFERENCES users (id) ON DELETE SET NULL,
  -- строка остаётся ради истории оплат
  deleted_at  DATE,
  CONSTRAINT recurring_payments_soft_delete CHECK (active = (deleted_at IS NULL))
);
CREATE INDEX recurring_payments_active_idx ON recurring_payments (active);

-- сумма и валюта копируются, чтобы история не менялась вместе с шаблоном
CREATE TABLE payment_occurrences (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recurring_payment_id BIGINT        NOT NULL REFERENCES recurring_payments (id) ON DELETE RESTRICT,
  month                CHAR(7)       NOT NULL CHECK (month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  name                 TEXT          NOT NULL,
  amount               NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  currency             CHAR(3)       NOT NULL CHECK (currency IN ('RUB', 'USD', 'EUR')),
  due_date             DATE          NOT NULL,
  paid_at              DATE,
  paid_by              BIGINT        REFERENCES users (id) ON DELETE SET NULL,
  created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CONSTRAINT payment_occurrences_one_per_month UNIQUE (recurring_payment_id, month),
  CONSTRAINT payment_occurrences_due_in_month CHECK (to_char(due_date, 'YYYY-MM') = month)
);
CREATE INDEX payment_occurrences_month_idx ON payment_occurrences (month, due_date);
CREATE INDEX payment_occurrences_unpaid_idx ON payment_occurrences (due_date) WHERE paid_at IS NULL;

-- одно напоминание на период, даже если бот запущен в нескольких экземплярах
CREATE TABLE reminders (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurrence_id BIGINT      NOT NULL REFERENCES payment_occurrences (id) ON DELETE CASCADE,
  channel       TEXT        NOT NULL DEFAULT 'telegram' CHECK (channel IN ('telegram')),
  send_date     DATE        NOT NULL,
  status        TEXT        NOT NULL DEFAULT 'sent' CHECK (status IN ('sent', 'failed')),
  sent_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  error         TEXT,
  CONSTRAINT reminders_once_per_occurrence UNIQUE (occurrence_id, channel)
);

CREATE TABLE settings (
  key        TEXT PRIMARY KEY,
  value      JSONB       NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
